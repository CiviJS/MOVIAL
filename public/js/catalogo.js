function construirMensaje(datos){
  var l = [];
  var tot = totalUnidades();
  /* Las familias se leen del producto (grupo), no de la inicial del id: un id "d01" es
     un dispositivo y no una señal reglamentaria. */
  var fam = [];
  var g = function(gr){
    if(fam.indexOf(gr) < 0) fam.push(gr);
  };
  carrito.forEach(function(it){
    var p = buscarProducto(it.id);
    g(p ? p.grupo : 'reg');
  });
  var soloDisp = fam.length === 1 && fam[0] === 'disp';
  var soloReg = fam.length === 1 && fam[0] === 'reg';
  var soloDem = fam.length === 1 && fam[0] === 'dem';
  var conDem = fam.indexOf('dem') > -1;
  var intro;
  if(soloDem){
    intro = 'Hola Movial, quiero cotizar demarcación vial.';
  }else if(soloReg){
    intro = 'Hola Movial, quiero cotizar señales de señalización vertical.';
  }else if(soloDisp){
    intro = 'Hola Movial, quiero cotizar dispositivos viales.';
  }else if(conDem){
    /* "señales preventivas y demarcación vial" no es una lista coherente */
    intro = 'Hola Movial, quiero cotizar demarcación vial y señalización de tránsito.';
  }else{
    var nombres = [];
    if(fam.indexOf('prev') > -1) nombres.push('preventivas');
    if(fam.indexOf('reg') > -1) nombres.push('reglamentarias');
    if(fam.indexOf('info') > -1) nombres.push('informativas');
    if(fam.indexOf('disp') > -1) nombres.push('dispositivos viales');
    var txtFam = nombres.length > 2
      ? nombres.slice(0, -1).join(', ') + ' y ' + nombres[nombres.length - 1]
      : nombres.join(' y ');
    intro = 'Hola Movial, quiero cotizar señales ' + txtFam + '.';
  }
  l.push(intro);
  l.push('');
  l.push('*Nombre:* ' + datos.nombre);
  l.push('*Empresa o entidad:* ' + datos.entidad);
  l.push('*WhatsApp/Teléfono:* ' + datos.telefono);
  l.push('');
  l.push('*Servicio que necesita:*');
  l.push(datos.servicio);
  l.push('');
  l.push('*Detalle de la solicitud*');
  l.push('----------------------------');
  carrito.forEach(function(it, i){
    l.push((i + 1) + '. ' + it.name);
    /* La categoría viaja en el carrito: deja claro qué es cada línea en carritos mixtos. */
    if(it.category) l.push('   - Categoría: ' + it.category);
    /* La demarcación se cobra por m, m² o unid: se indica la unidad real, no "unidades" */
    l.push('   - Cantidad: ' + it.quantity + (it.unit ? ' ' + it.unit : ' ' + plural(it.quantity, 'unidad', 'unidades')));
    if(it.color) l.push('   - Color: ' + it.color);
    if(it.pintura) l.push('   - Tipo de pintura: ' + it.pintura);
    if(it.superficie) l.push('   - Superficie: ' + it.superficie);
    if(it.asesoria) l.push('   - Asesoría técnica: solicitada. Un asesor define medidas y materiales con el cliente.');
    if(it.details) l.push('   - Detalles: ' + it.details);
  });
  l.push('');
  var uni = unidadesPorUnidad();
  if(uni.orden.length){
    /* Sumar metros y unidades como si fueran piezas daría un total sin sentido */
    var partes = [];
    if(uni.libre) partes.push(uni.libre + ' ' + plural(uni.libre, 'señal', 'señales'));
    uni.orden.forEach(function(k){ partes.push(uni.porUnidad[k] + ' ' + k); });
    l.push('*Totales por unidad:* ' + partes.join(' · ') + '* (' + textoReferencias() + ')');
  }else{
    l.push('*Total: ' + tot + ' ' + plural(tot, 'unidad', 'unidades') + '* ('
      + plural(carrito.length, '1 referencia', carrito.length + ' referencias') + ')');
  }
  if(datos.mensaje){
    l.push('');
    l.push('*Cuéntenos brevemente:*');
    l.push(datos.mensaje);
  }
  l.push('');
  l.push('Quedo atento a la confirmación de disponibilidad, medidas y precio. Gracias.');
  return l.join('\n');
}

