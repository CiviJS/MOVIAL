/* +/− / quitar: compartido por el drawer y la sección colapsable */
function accionItem(e){
  var b = e.target.closest('button');
  if(!b) return;
  var i;
  if(b.hasAttribute('data-quitar')){
    i = parseInt(b.getAttribute('data-quitar'), 10);
    if(carrito[i]) carrito.splice(i, 1);
  }else if(b.hasAttribute('data-menos')){
    i = parseInt(b.getAttribute('data-menos'), 10);
    if(!carrito[i]) return;
    carrito[i].quantity -= 1;
    if(carrito[i].quantity < 1) carrito.splice(i, 1);
  }else if(b.hasAttribute('data-mas')){
    i = parseInt(b.getAttribute('data-mas'), 10);
    if(!carrito[i]) return;
    if(carrito[i].quantity < CAT_MAX) carrito[i].quantity += 1;
  }else{
    return;
  }
  guardarCarrito();
  pintarCarrito();
}
