  function actualizarFlechas(){
  if(!catPest || !catPestWrap) return;
  var max = catPest.scrollWidth - catPest.clientWidth;
  var dcha = max - catPest.scrollLeft;
  var hay = max > 2;
  catPestWrap.classList.toggle('mas-dcha', hay && dcha > 2);
  catPestWrap.classList.toggle('mas-izq', hay && catPest.scrollLeft > 2);
  if(catPestDer) catPestDer.hidden = !hay || dcha <= 2;
  if(catPestIzq) catPestIzq.hidden = !hay || catPest.scrollLeft <= 2;
  }
  function moverPestanas(dir){
  if(!catPest) return;
  var paso = Math.max(170, Math.round(catPest.clientWidth * 0.6));
  catPest.scrollBy({ left: dir * paso, behavior: 'smooth' });
  }
  /* Si la pestaña activa queda fuera de la vista, la Traemos. Con scroll por
     getBoundingClientRect y no offsetLeft, que depende del offsetParent. */
  function verPestanaActiva(b){
  if(!catPest || !b) return;
  var pr = catPest.getBoundingClientRect(), br = b.getBoundingClientRect();
  if(br.left < pr.left + PEST_HOLGA - 12){
  catPest.scrollBy({ left: br.left - pr.left - PEST_HOLGA + 12, behavior: 'smooth' });
  } else if(br.right > pr.right - PEST_HOLGA + 12){
  catPest.scrollBy({ left: br.right - pr.right + PEST_HOLGA - 12, behavior: 'smooth' });
  }
  }
  if(catPestDer) catPestDer.addEventListener('click', function(){ moverPestanas(1); });
  if(catPestIzq) catPestIzq.addEventListener('click', function(){ moverPestanas(-1); });
  if(catPest) catPest.addEventListener('scroll', actualizarFlechas, { passive: true });
  window.addEventListener('resize', actualizarFlechas);
  if(catPestDer) catPestDer.addEventListener('click', function(){
  /* un segundo clic lleva al final, para no tener que pulsarlo cinco veces */
  var max = catPest.scrollWidth - catPest.clientWidth;
  if(Math.abs(max - catPest.scrollLeft) < catPest.clientWidth * 0.9){
  catPest.scrollTo({ left: max, behavior: 'smooth' });
  }
  });

