/* Búsqueda tolerante: sin tildes, plural -s y variante prohibido/prohibida.
   El plural se recorta solo con la "s" final: con [aeiou]s "Cebras" quedaba
   "cebr" y buscar "cebra" no encontraba nada. */
function norm(t){
  if(t === null || t === undefined) return '';
  return String(t).toLowerCase().normalize('NFD')
    .replace(/[\u0300-\u036f]/g,'')
    .replace(/s\b/g,'')
    .replace(/\s+/g,' ')
    .trim();
}
function normFlex(t){
  return norm(t).replace(/[aeiou]\b/g,'').trim();
}

