/* "Señales Preventivas · Preventivas" es redundante: se emite solo el
   nombre completo cuando el subtipo no aporta información nueva. */
function etiquetaCategoria(categoria, subtipo){
  if(!categoria) return '';
  if(subtipo && String(categoria).replace(/^Señales\s+/i, '') !== String(subtipo)){
    return categoria + ' · ' + subtipo;
  }
  return categoria;
}

