/* ---------- Carrito ---------- */
function totalUnidades(){
  var n = 0;
  for(var i = 0; i < carrito.length; i++) n += carrito[i].quantity;
  return n;
}
/* La demarcación se mide en m, m² o unid, así que sumar todo como "señales"
   sería falso ("250 m + 8 unid = 258 señales"). Se agrupa por unidad y los
   ítems que no la traen (señales y dispositivos) se cuentan aparte. */
function unidadesPorUnidad(){
  var porUnidad = {}, orden = [], libre = 0;
  carrito.forEach(function(it){
    if(it.unit){
      if(!(it.unit in porUnidad)){ porUnidad[it.unit] = 0; orden.push(it.unit); }
      porUnidad[it.unit] += it.quantity;
    }else{
      libre += it.quantity;
    }
  });
  return { porUnidad: porUnidad, orden: orden, libre: libre };
}
function resumenCarrito(){
  var u = unidadesPorUnidad();
  if(!u.orden.length){
    var n = totalUnidades();
    return n + ' ' + plural(n, 'señal', 'señales');
  }
  var partes = [];
  if(u.libre) partes.push(u.libre + ' ' + plural(u.libre, 'señal', 'señales'));
  u.orden.forEach(function(k){ partes.push(u.porUnidad[k] + ' ' + k); });
  return partes.join(' · ');
}
function textoReferencias(){
  return plural(carrito.length, '1 referencia', carrito.length + ' referencias');
}
/* En la barra solo cabe una cifra. Encadenar "6 señales · 7 m · 1 unid" obliga a
   leer la línea y no dice cuántas cosas se agregaron; el desglose por unidad se
   queda en la sección de cotización, que sí tiene sitio y etiqueta. */
function resumenBarra(){
  var n = numeroCarrito();
  return n + ' ' + plural(n, 'ítem', 'ítems') + ' en tu cotización';
}
/* En los contadores compactos (badge, header) no cabe "250 m · 8 unid": si hay
   unidades se muestra el número de referencias, que sí es comparable. */
function numeroCarrito(){
  return unidadesPorUnidad().orden.length ? carrito.length : totalUnidades();
}

