function leerCarrito(){
  try{
    var crudo = localStorage.getItem(CAT_CLAVE);
    if(!crudo) return [];
    var arr = JSON.parse(crudo);
    if(!Array.isArray(arr)) return [];
    var salida = [];
    arr.forEach(function(i){
      if(!i || !i.id || !i.name) return;
      var q = parseInt(i.quantity, 10);
      if(isNaN(q) || q < 1) q = 1;
      if(q > CAT_MAX) q = CAT_MAX;
      var p = buscarProducto(String(i.id));
      /* imagePath es el campo actual; img es el legacy de carritos guardados antes */
      var img = String(i.imagePath || i.img || '');
      if(!img && p) img = p.img;
      salida.push({
        id: String(i.id),
        name: String(i.name),
        category: String(i.category || CAT_CATEGORIA + ' · ' + CAT_SUBTIPO),
        imagePath: img,
        quantity: q,
        details: String(i.details || '').slice(0, 400)
      });
    });
    return salida;
  }catch(e){ return []; }
}
