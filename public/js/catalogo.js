/* --- Estado global: [{ id, name, category, imagePath, quantity, details }]
   y para demarcación además { color, unit } --- */
function leerCarrito(){
  try{
    var crudo = localStorage.getItem(CAT_CLAVE);
    if(!crudo) return [];
    var arr = JSON.parse(crudo);
    if(!Array.isArray(arr)) return [];
    var salida = [];
    arr.forEach(function(i){
      if(!i || !i.id || !i.name) return;
      var q = parseInt(i.quantity, 10);
      if(isNaN(q) || q < 1) q = 1;
      if(q > CAT_MAX) q = CAT_MAX;
      var p = buscarProducto(String(i.id));
      /* imagePath es el campo actual; img es el legacy de carritos guardados antes */
      var img = String(i.imagePath || i.img || '');
      if(!img && p) img = p.img;
      var item = {
        id: String(i.id),
        name: String(i.name),
        category: String(i.category || CAT_CATEGORIA + ' · ' + CAT_SUBTIPO),
        imagePath: img || '',
        quantity: q,
        details: String(i.details || '').slice(0, 400)
      };
      /* La demarcación se cotiza por unidad de obra y con color: se conservan
         solo si siguen siendo valores válidos de la lista cerrada. */
      var col = String(i.color || '');
      if(COLORES_DEM.some(function(c){ return c.nombre === col; })) item.color = col;
      var uni = String(i.unit || '');
      if(infoUnidad(uni)) item.unit = infoUnidad(uni).corto;
      /* Pintura y superficie también son listas cerradas: un valor viejo o
         manipulado no debe llegar al mensaje como si fuera una especificación. */
      var pin = opcionDe(PINTURAS_DEM, String(i.pintura || ''));
      if(pin) item.pintura = pin.v;
      var sup = opcionDe(SUPERFICIES_DEM, String(i.superficie || ''));
      if(sup) item.superficie = sup.v;
      if(i.asesoria === true) item.asesoria = true;
      salida.push(item);
    });
    return salida;
  }catch(e){ return []; }
}
