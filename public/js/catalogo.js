function miniaturasCarrito(){
  var out = '';
  var tope = Math.min(carrito.length, 4);
  for(var i = 0; i < tope; i++){
    var it = carrito[i];
    if(it.imagePath){
      out += '<img src="' + esc(it.imagePath) + '" alt="" loading="lazy" decoding="async">';
    }else{
      out += htmlVacio(it, 'dem-mini');
    }
  }
  if(carrito.length > tope){
    out += '<span class="mas">+' + (carrito.length - tope) + '</span>';
  }
  return out;
}

